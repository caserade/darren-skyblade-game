import bpy,bmesh,json,os
p=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
bpy.ops.wm.open_mainfile(filepath=os.path.join(p,'chomprex/source/chomprex-sculpt-stage.blend'))
o=bpy.data.objects['ChompRex_ContinuousBody'];bpy.context.view_layer.objects.active=o;bpy.ops.object.select_all(action='DESELECT');o.select_set(True)
o.data.remesh_voxel_size=.045;bpy.ops.object.voxel_remesh()
bm=bmesh.new();bm.from_mesh(o.data)
print('TOPOLOGY',json.dumps({'verts':len(bm.verts),'edges':len(bm.edges),'faces':len(bm.faces),'edge_nonmanifold':sum(not e.is_manifold for e in bm.edges),'vertex_nonmanifold':sum(not v.is_manifold for v in bm.verts),'edge_noncontiguous':sum(not e.is_contiguous for e in bm.edges),'zero_faces':sum(f.calc_area()<1e-10 for f in bm.faces),'zero_edges':sum(e.calc_length()<1e-7 for e in bm.edges)}))
bmesh.ops.remove_doubles(bm,verts=bm.verts,dist=.0001)
bmesh.ops.dissolve_degenerate(bm,dist=.0001,edges=bm.edges)
bmesh.ops.triangulate(bm,faces=bm.faces[:],quad_method='BEAUTY',ngon_method='BEAUTY')
bmesh.ops.dissolve_degenerate(bm,dist=.0001,edges=bm.edges)
bmesh.ops.recalc_face_normals(bm,faces=bm.faces);bm.to_mesh(o.data);bm.free();o.data.update()
bpy.context.view_layer.objects.active=o;bpy.ops.object.select_all(action='DESELECT');o.select_set(True)
r=bpy.ops.object.quadriflow_remesh(target_faces=15000,use_mesh_symmetry=False,use_preserve_sharp=False,use_preserve_boundary=False,smooth_normals=True,seed=14)
print('CLEAN_RETOPO',r,len(o.data.polygons))
